const image = (key, file, widthCm, text) => {
  figNo++; figIndex[key] = figNo;
  const buf = fs.readFileSync(FIG + file);
  // read jpeg size
  let w = 0, h = 0, i = 2;
  while (i < buf.length) {
    const marker = buf[i + 1], len = buf.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xc2) { h = buf.readUInt16BE(i + 5); w = buf.readUInt16BE(i + 7); break; }
    i += 2 + len;
  }
  const pxW = Math.round(widthCm / 2.54 * 96), pxH = Math.round(pxW * h / w);
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, keepNext: true, spacing: { before: 120 },
      children: [new ImageRun({ type: "jpg", data: buf, transformation: { width: pxW, height: pxH } })] }),
    caption(text),
  ];
};
